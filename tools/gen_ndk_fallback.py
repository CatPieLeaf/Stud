#!/usr/bin/env python3
"""Writes the source of Stud's NDK fallback library.

The engine is linked against Android's NDK libraries, and Android's loader
refuses a library with a single import nothing provides. Stud implements
those libraries itself, function by function, as the engine needed them,
so every engine update that started using one more NDK function stopped
Stud from loading the engine at all (Roblox 2.744: AImageReader_*).

This takes every public symbol of every NDK library -- the NDK's own stub
libraries are that list, at the newest API level it has -- and removes each
one something Stud already loads defines: its own libraries, bionic's, and
Process B's executable. What is left is defined here, once:

  - a function logs its own name the first time it is called and
    returns 0;
  - a variable (in practice a key string or an interface id pointer)
    points at an empty string, so it reads as "" or as zeroes.

Nothing in the result can shadow a real implementation, because nothing
real is in it. It must still never be loaded globally: the engine also
looks NDK functions up by name to see whether the device has them, and
there a stub would turn "absent" into a function that returns 0 (see
runtime/CMakeLists.txt for how it is reached instead).

Usage:
  gen_ndk_fallback.py --nm NM --stubs DIR --out FILE.c
                      [--have-dir DIR ...] [--have FILE ...]
                      [--skip-lib NAME ...] [--fallback-name libNAME.so]
"""

import argparse
import os
import re
import subprocess
import sys

IDENTIFIER = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def newest_api_dir(root):
    levels = [d for d in os.listdir(root) if d.isdigit() and os.path.isdir(os.path.join(root, d))]
    if not levels:
        sys.exit(f'gen_ndk_fallback: no API level directories under {root}')
    return os.path.join(root, max(levels, key=int))


def exported(nm, path):
    """{name: nm type letter} of what `path` defines in its dynamic table."""
    out = subprocess.run([nm, '-D', '--defined-only', path], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f'gen_ndk_fallback: {nm} failed on {path}: {out.stderr.strip()}')
    names = {}
    for line in out.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 3:
            names[parts[-1].split('@')[0]] = parts[-2]
    return names


def is_elf(path):
    try:
        with open(path, 'rb') as f:
            return f.read(4) == b'\x7fELF'
    except OSError:
        return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--nm', required=True)
    ap.add_argument('--stubs', required=True, help='the NDK sysroot lib/<triple> directory')
    ap.add_argument('--have-dir', action='append', default=[])
    ap.add_argument('--have', action='append', default=[])
    ap.add_argument('--skip-lib', action='append', default=[],
                    help='an NDK library supplied whole elsewhere, never stood in for')
    ap.add_argument('--fallback-name', help='our own output, never counted as something Stud has')
    ap.add_argument('--out', required=True)
    args = ap.parse_args()

    have = set()
    have_files = list(args.have)
    for d in args.have_dir:
        for name in sorted(os.listdir(d)):
            path = os.path.join(d, name)
            if name == args.fallback_name or os.path.islink(path):
                continue
            if '.so' in name and os.path.isfile(path) and is_elf(path):
                have_files.append(path)
    for path in have_files:
        have |= set(exported(args.nm, path))

    api_dir = newest_api_dir(args.stubs)
    functions, variables = {}, {}
    for lib in sorted(os.listdir(api_dir)):
        if not lib.endswith('.so') or lib in args.skip_lib:
            continue
        for name, kind in exported(args.nm, os.path.join(api_dir, lib)).items():
            if name in have or not IDENTIFIER.match(name):
                continue
            (functions if kind in 'TtWwi' else variables).setdefault(name, lib)

    lines = [
        f'// Generated by tools/gen_ndk_fallback.py from {api_dir}. Do not edit.',
        '// Every public NDK symbol nothing else Stud loads defines; see the script.',
        '#include <stdio.h>',
        '',
        'static void stud_ndk_fallback_called(const char* name, const char* lib, int* said) {',
        '    if (__atomic_exchange_n(said, 1, __ATOMIC_RELAXED)) return;',
        '    fprintf(stderr, "stud: the engine called %s (%s), which Stud does not implement; "',
        '                    "it was given 0\\n", name, lib);',
        '}',
        '',
    ]
    for name, lib in sorted(functions.items()):
        lines.append(f'static int said_{name};')
        lines.append(f'void* {name}(void) {{ stud_ndk_fallback_called("{name}", "{lib}", &said_{name}); '
                     f'return 0; }}')
    for name in sorted(variables):
        lines.append(f'const void* {name} = "";')
    with open(args.out + '.tmp', 'w') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(args.out + '.tmp', args.out)

    print(f'gen_ndk_fallback: {len(functions)} function(s), {len(variables)} variable(s) '
          f'from {os.path.basename(api_dir)}')


if __name__ == '__main__':
    main()
