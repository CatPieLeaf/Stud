#!/usr/bin/env python3
"""Writes render-host/include/stud/vulkan_registry.inc from the Vulkan registry.

    tools/gen_vulkan_registry.py <vk.xml> <vulkan_core.h> > render-host/include/stud/vulkan_registry.inc

vk.xml comes from KhronosGroup/Vulkan-Headers, the same version as the header.
The output is committed: the engine's client builds against the NDK's older
headers, and both processes have to agree on every struct.

What it holds:
 - the size of every pNext struct that is plain data. One that holds a pointer
   or a handle means nothing in the other process, so it stays out and is
   dropped with a log line, as any unknown struct is;
 - the commands each extension always needs, so one Stud cannot forward is not
   offered to the engine. A command only an extra dependency brings in (the
   device-group calls of VK_KHR_swapchain) does not count;
 - the commands of each core version, so the API version Stud reports is the
   one it can honour.
"""
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET


def main(xml_path, header):
    reg = ET.parse(xml_path).getroot()
    header_text = open(header).read()

    handles = {t.findtext("name") or t.get("name") for t in reg.findall("types/type[@category='handle']")}
    structs = {t.get("name"): t for t in reg.findall("types/type")
               if t.get("category") in ("struct", "union")}
    aliases = {t.get("name"): t.get("alias") for t in reg.findall("types/type") if t.get("alias")}

    def plain(name, seen=()):
        name = aliases.get(name, name)
        t = structs.get(name)
        if t is None:
            return name not in handles and not name.startswith("PFN_")
        if name in seen:
            return False
        for m in t.findall("member"):
            mname = m.findtext("name")
            if mname in ("sType", "pNext"):
                continue
            text = "".join(m.itertext())
            if "*" in text or not plain(m.findtext("type"), seen + (name,)):
                return False
        return True

    nodes = {}
    for name, t in structs.items():
        if t.get("structextends") is None or t.get("alias"):
            continue
        members = t.findall("member")
        if not members or members[0].findtext("name") != "sType":
            continue
        s_type = members[0].get("values")
        if s_type is None or not plain(name):
            continue
        if re.search(r"\b" + name + r"\b;?\s*$", header_text, re.M) is None:
            continue
        if f"}} {name};" in header_text:
            nodes[name] = s_type

    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "sizes.c")
        with open(src, "w") as f:
            f.write(f'#include "{header}"\n#include <stdio.h>\nint main(void) {{\n')
            for name, s_type in nodes.items():
                f.write(f'printf("%u %zu\\n", (unsigned){s_type}, sizeof({name}));\n')
            f.write("return 0;\n}\n")
        exe = os.path.join(tmp, "sizes")
        subprocess.check_call(["cc", "-I", os.path.dirname(os.path.dirname(header)), src, "-o", exe])
        sizes = sorted(tuple(map(int, l.split()))
                       for l in subprocess.check_output([exe], text=True).splitlines())

    def commands_of(require):
        return [c.get("name") for c in require.findall("command")]

    def blob(commands):
        return "".join(c + "\\0" for c in commands)

    extensions = {}
    for e in reg.findall("extensions/extension"):
        if "vulkan" not in e.get("supported", "").split(","):
            continue
        commands = []
        for r in e.findall("require"):
            if r.get("depends") is None and r.get("api", "vulkan") == "vulkan":
                commands += commands_of(r)
        extensions[e.get("name")] = list(dict.fromkeys(commands))

    core = {}
    for f in reg.findall("feature"):
        m = re.fullmatch(r"VK_(?:[A-Z]+_)?VERSION_1_(\d+)", f.get("name"))
        if m is None or "vulkansc" == f.get("api"):
            continue
        minor = int(m.group(1))
        for r in f.findall("require"):
            core.setdefault(minor, []).extend(commands_of(r))

    all_commands = {c.get("name") or c.findtext("proto/name") for c in reg.findall("commands/command")}

    out = sys.stdout
    version = re.search(r"#define VK_HEADER_VERSION (\d+)", header_text).group(1)
    out.write(f"// Generated by tools/gen_vulkan_registry.py from Vulkan header {version}. Do not edit.\n\n")
    out.write(f"constexpr int kRegistryCommandCount = {len(all_commands)};\n\n")
    out.write("constexpr ChainNodeSize kChainNodeSizes[] = {\n")
    for s_type, size in sizes:
        out.write(f"    {{{s_type}u, {size}u}},\n")
    out.write("};\n\n")
    out.write("constexpr CoreCommands kCoreCommands[] = {\n")
    for minor in sorted(core):
        out.write(f'    {{{minor}, "{blob(dict.fromkeys(core[minor]))}"}},\n')
    out.write("};\n\n")
    out.write("constexpr ExtensionCommands kExtensionCommands[] = {\n")
    for name in sorted(extensions):
        if extensions[name]:
            out.write(f'    {{"{name}", "{blob(extensions[name])}"}},\n')
    out.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
