#!/usr/bin/env python3
"""Writes android-glue/src/engine_contract.inc: what Stud expects of Roblox.

    tools/gen_engine_contract.py <apk or bundle> > android-glue/src/engine_contract.inc

Run it from the repository root against a Roblox Stud works with, after adding
a call into the engine or a Java member. It records each engine entry point
Stud calls by its full name, with the signature the APK declares for it, and
the names of the Java members Stud provides. apk_check.cpp compares a new APK
against that.
"""
import io
import os
import re
import struct
import sys
import zipfile

# Without these the session cannot start; see engine_v2_bridge.cpp.
REQUIRED = {
    "nativeSetAssetPath", "nativePreloadFlagOverrides", "nativeAppBridgeSetInitParams",
    "nativeInitClientSettings", "nativeGameGlobalInit", "nativeAppBridgeV2InitWithParams",
    "nativeAppBridgeV2StartAppWithParams", "initializeNativeCode",
}


def uleb(b, p):
    r = s = 0
    while True:
        x = b[p]
        p += 1
        r |= (x & 0x7f) << s
        s += 7
        if not x & 0x80:
            return r, p


def read_dex(b, natives, members):
    ss, so, ts, to, ps, po, fs, fo, ms, mo, cs, co = struct.unpack_from("<12I", b, 0x38)

    def string(i):
        _, p = uleb(b, struct.unpack_from("<I", b, so + i * 4)[0])
        return b[p:b.index(0, p)].decode("utf8", "replace")

    def typ(i):
        return string(struct.unpack_from("<I", b, to + i * 4)[0])

    def proto(i):
        _, ret, par = struct.unpack_from("<III", b, po + i * 12)
        args = ""
        if par:
            n = struct.unpack_from("<I", b, par)[0]
            args = "".join(typ(struct.unpack_from("<H", b, par + 4 + k * 2)[0]) for k in range(n))
        return "(" + args + ")" + typ(ret)

    for i in range(cs):
        cls, _, _, _, _, _, data, _ = struct.unpack_from("<8I", b, co + i * 32)
        if not data:
            continue
        name = typ(cls)[1:-1]
        p = data
        sf, p = uleb(b, p)
        inf, p = uleb(b, p)
        dm, p = uleb(b, p)
        vm, p = uleb(b, p)
        names = members.setdefault(name, set())
        for count in (sf, inf):
            idx = 0
            for _ in range(count):
                d, p = uleb(b, p)
                _, p = uleb(b, p)
                idx += d
                names.add(string(struct.unpack_from("<I", b, fo + idx * 8 + 4)[0]))
        for count in (dm, vm):
            idx = 0
            for _ in range(count):
                d, p = uleb(b, p)
                flags, p = uleb(b, p)
                _, p = uleb(b, p)
                idx += d
                _, pr, nm = struct.unpack_from("<HHI", b, mo + idx * 8)
                method = string(nm)
                names.add(method)
                if flags & 0x100:
                    natives[(name, method)] = proto(pr)


def mangle(text):
    return (text.replace("_", "_1").replace("$", "_00024").replace("/", "_"))


def main(apk):
    z = zipfile.ZipFile(apk)
    if "base.apk" in z.namelist():
        z = zipfile.ZipFile(io.BytesIO(z.read("base.apk")))
    natives, members = {}, {}
    for n in z.namelist():
        if re.fullmatch(r"classes\d*\.dex", n):
            read_dex(z.read(n), natives, members)

    src = ""
    for root in ["runtime", "android-glue"]:
        for dp, _, fn in os.walk(root):
            if "patches" in dp:
                continue
            for f in fn:
                if f.endswith((".cpp", ".h")):
                    src += open(os.path.join(dp, f), errors="ignore").read() + "\n"
    joined = re.sub(r'"\s*\n\s*"', "", src)
    calls = set(re.findall(r'"(Java_[A-Za-z0-9_]+)"', joined))
    by_symbol = {"Java_" + mangle(c) + "_" + mangle(m): (c, m, s) for (c, m), s in natives.items()}

    quoted = set(re.findall(r'"([A-Za-z_][A-Za-z0-9_]{2,})"', src))
    classes = sorted(set(re.findall(r'DEFINE_CLASS_NAME\(\s*"(com/roblox/[^"]+)"', src)))

    out = sys.stdout
    out.write("// Generated by tools/gen_engine_contract.py. Do not edit.\n\n")
    out.write("constexpr EngineEntryPoint kEngineEntryPoints[] = {\n")
    for symbol in sorted(calls):
        if symbol in by_symbol:
            c, m, s = by_symbol[symbol]
            out.write(f'    {{"{symbol}", "{c}.{m}", "{s}", {"true" if m in REQUIRED else "false"}}},\n')
    out.write("};\n\n")
    out.write("constexpr const char* kStudJavaClasses[] = {\n")
    for c in classes:
        if c in members:
            out.write(f'    "{c}",\n')
    out.write("};\n\n")
    known = sorted({n for c in classes for n in members.get(c, ()) if n in quoted})
    out.write("constexpr const char* kStudJavaMembers[] = {\n")
    for n in known:
        out.write(f'    "{n}",\n')
    out.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
